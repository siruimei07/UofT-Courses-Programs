import { expect, test, type Page } from '@playwright/test'
import { PROFILE_STORAGE_KEY } from '../../src/domain/profile'

async function loaded(page: Page) {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: '看见课程之间的联系.' })).toBeVisible()
}
async function selectCourse(page: Page, code: string) {
  await page.getByRole('button', { name: '列表视图', exact: true }).click()
  await page.getByRole('searchbox', { name: '搜索课程或专业' }).fill(code)
  await page.getByRole('searchbox', { name: '搜索课程或专业' }).press('Escape')
  await page.getByRole('button', { name: new RegExp(`^查看 ${code} `) }).click()
  await expect(page.getByRole('complementary', { name: '课程详情' }).getByRole('heading', { name: code, exact: true })).toBeVisible()
}

test('production repository subpath, graph controls, conditional labels, and full-catalog search', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const response = await page.goto('./')
  expect(response?.status()).toBe(200)
  await expect(page).toHaveTitle(/UTM Course Atlas/)
  await expect(page.getByRole('heading', { name: '看见课程之间的联系.' })).toBeVisible()
  await expect(page.locator('.react-flow__node-course').first()).toBeVisible()
  await page.getByRole('button', { name: '放大', exact: true }).click()
  await page.getByRole('button', { name: '缩小', exact: true }).click()
  await page.getByRole('button', { name: '适配全图', exact: true }).click()
  await page.getByRole('button', { name: '重置视图', exact: true }).click()
  await selectCourse(page, 'ANT202H5')
  await expect(page.getByRole('complementary', { name: '课程详情' }).getByText('ANT101H5 or BIO152H5', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '在图中展开关联课程' }).click()
  await expect(page.locator('.react-flow__node-course.selected')).toBeVisible()
  await expect(page.locator('.react-flow__edge')).not.toHaveCount(0)
  await expect(page.getByText('关联视图', { exact: true })).toBeVisible()
  const data = await page.request.get('data/catalog.json')
  expect(data.status()).toBe(200)
  const catalog = await data.json()
  expect(catalog.metadata.complete).toBe(true)
  expect(catalog.courses.length).toBeGreaterThan(2000)
  expect(catalog.programs.length).toBeGreaterThan(150)
  await page.reload()
  await expect(page.locator('.react-flow__node-course').first()).toBeVisible()
  expect(errors).toEqual([])
})

test('planned versus completed changes eligibility and records persist across refresh', async ({ page }) => {
  await loaded(page)
  await page.getByRole('button', { name: '我的档案', exact: true }).click()
  await page.getByRole('checkbox', { name: /我已录入全部已完成课程/ }).check()
  await page.getByRole('button', { name: '完成', exact: true }).click()
  await selectCourse(page, 'ANT101H5')
  await page.getByLabel('我的修读状态', { exact: true }).selectOption('planned')
  await selectCourse(page, 'ANT202H5')
  await expect(page.locator('.eligibility-card')).toContainText('缺条件')
  await selectCourse(page, 'ANT101H5')
  await page.getByLabel('我的修读状态', { exact: true }).selectOption('completed')
  await page.getByRole('spinbutton', { name: '课程成绩' }).fill('78')
  await selectCourse(page, 'ANT202H5')
  await expect(page.locator('.eligibility-card')).toContainText('条件已满足')
  await page.reload()
  await selectCourse(page, 'ANT101H5')
  await expect(page.getByLabel('我的修读状态', { exact: true })).toHaveValue('completed')
  await expect(page.getByRole('spinbutton', { name: '课程成绩' })).toHaveValue('78')
  await page.getByRole('checkbox', { name: '隐藏已完成' }).check()
  await expect(page.getByRole('heading', { name: '没有找到匹配的课程' })).toBeVisible()
})

