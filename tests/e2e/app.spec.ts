test('profile import validates, exports valid JSON, and clear resets stored state', async ({ page }) => {
  await loaded(page)
  await page.getByRole('button', { name: '我的档案', exact: true }).click()
  await page.getByLabel('导入档案文件').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"schemaVersion":999}') })
  await expect(page.getByRole('alert')).toContainText('不支持此档案版本')
  const fixture = { schemaVersion: 1, recordComplete: true, admittedPrograms: [], courses: [{ courseId: 'UTM:ANT101H5', status: 'completed', grade: 81 }] }
  await page.getByLabel('导入档案文件').setInputFiles({ name: 'profile.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture)) })
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('textbox', { name: '入学 cohort', exact: true }).fill('   ')
  await page.reload()
  await page.getByRole('button', { name: '我的档案', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出档案' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('utm-student-profile.json')
  const stream = await download.createReadStream()
  const parts: Buffer[] = []
  for await (const part of stream!) parts.push(Buffer.from(part))
  expect(JSON.parse(Buffer.concat(parts).toString('utf8'))).toEqual(fixture)
  await page.getByRole('button', { name: '清除本机档案' }).click()
  await page.getByRole('button', { name: '确认清除' }).click()
  const stored = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), PROFILE_STORAGE_KEY)
  expect(stored.courses).toHaveLength(0)
  expect(stored.recordComplete).toBe(false)
})

