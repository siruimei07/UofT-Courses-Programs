  page.on('pageerror', error => errors.push(error.message))
  await loaded(page)
  const close = page.getByRole('button', { name: '关闭课程详情' })
  if (await close.count()) await close.click()
  await page.getByRole('complementary', { name: '目录导航' }).getByRole('button', { name: /^HIS History/ }).click()
  await page.getByRole('button', { name: '显示更多' }).click()
